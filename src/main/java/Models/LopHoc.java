package Models;

public class LopHoc {
    private int maLop;
    private String maLopHienThi;
    private String tenLop;
    private int maChuyenNganh;
    private String tenChuyenNganh;
    private String tenKhoa;

    public LopHoc() {
    }

    public int getMaLop() {
        return maLop;
    }

    public void setMaLop(int maLop) {
        this.maLop = maLop;
    }

    public String getMaLopHienThi() {
        return maLopHienThi;
    }

    public void setMaLopHienThi(String maLopHienThi) {
        this.maLopHienThi = maLopHienThi;
    }

    public String getTenLop() {
        return tenLop;
    }

    public void setTenLop(String tenLop) {
        this.tenLop = tenLop;
    }

    public String getTenChuyenNganh() {
        return tenChuyenNganh;
    }

    public void setTenChuyenNganh(String tenChuyenNganh) {
        this.tenChuyenNganh = tenChuyenNganh;
    }

    public String getTenKhoa() {
        return tenKhoa;
    }

    public void setTenKhoa(String tenKhoa) {
        this.tenKhoa = tenKhoa;
    }

    public int getMaChuyenNganh() {
        return maChuyenNganh;
    }

    public void setMaChuyenNganh(int maChuyenNganh) {
        this.maChuyenNganh = maChuyenNganh;
    }
}
